"""Shared rendering helpers for the Python emitter."""

from __future__ import annotations

import json

MARKER = "# Code generated by pons-emit-python. DO NOT EDIT."


def docstring(text: str) -> str:
    cleaned = " ".join(text.split())
    return json.dumps(cleaned, ensure_ascii=False)


def literal(value: object) -> str:
    return repr(value)


def start(module_doc: str) -> str:
    return f"{MARKER}\n{docstring(module_doc)}\n\n"


def indent(lines: list[str], level: int = 1) -> list[str]:
    prefix = "    " * level
    return [prefix + line if line else line for line in lines]
