"""Shared helpers for the emitter tests."""

from __future__ import annotations

import copy
import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
REPOSITORY = ROOT.parents[1]
FIXTURES = Path(__file__).resolve().parent / "fixtures"
SPEC_FIXTURES = REPOSITORY / "spec" / "fixtures"
MARKER = "# Code generated by pons-emit-python. DO NOT EDIT."


def load(name: str) -> dict[str, Any]:
    return json.loads((FIXTURES / name).read_text(encoding="utf-8"))


def load_spec(name: str) -> dict[str, Any]:
    return json.loads((SPEC_FIXTURES / name).read_text(encoding="utf-8"))


def request(
    document: dict[str, Any],
    *,
    options: dict[str, Any] | None = None,
    mode: str = "strict",
    target: str = "python",
    protocol: int = 3,
) -> dict[str, Any]:
    return {
        "protocol": protocol,
        "source_ir_version": "0.3",
        "mode": mode,
        "ir": document,
        "options": {} if options is None else options,
        "target": target,
    }


def emit(
    document: dict[str, Any],
    *,
    options: dict[str, Any] | None = None,
    mode: str = "strict",
    target: str = "python",
    protocol: int = 3,
) -> dict[str, Any]:
    from pons_emit_python.emit import emit as run

    payload = request(
        document,
        options=options,
        mode=mode,
        target=target,
        protocol=protocol,
    )
    return run(json.dumps(payload).encode("utf-8"))


def emit_raw(payload: object) -> dict[str, Any]:
    from pons_emit_python.emit import emit as run

    return run(json.dumps(payload).encode("utf-8"))


def write_files(response: dict[str, Any], directory: Path) -> list[Path]:
    written: list[Path] = []
    for file in response["files"]:
        destination = directory / file["path"]
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(file["content"], encoding="utf-8")
        written.append(destination)
    return written


def subjects(document: dict[str, Any]) -> set[str]:
    result = {f"types.{type_id}" for type_id in document.get("types", {})}
    for operation in document.get("operations", []):
        result.add("operations." + operation_path(operation["id"]))
    return result


def operation_path(segments: list[list[str]]) -> str:
    return ".".join(
        "_".join(
            word.replace("%", "%25").replace(".", "%2E").replace("_", "%5F")
            for word in segment
        )
        for segment in segments
    )


def coverage_subjects(response: dict[str, Any]) -> list[str]:
    coverage = response["coverage"]
    return (
        list(coverage["exact"])
        + list(coverage["opaque"])
        + list(coverage["lossy"])
        + list(coverage["unsupported"])
    )


