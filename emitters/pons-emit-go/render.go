package main

import (
	"fmt"
	"sort"
	"strings"
)

const generatedMarker = "// Code generated by pons-emit-go. DO NOT EDIT.\n"

func writeFileHeader(builder *strings.Builder, pkg string, imports []string) {
	builder.WriteString(generatedMarker)
	builder.WriteString("\npackage ")
	builder.WriteString(pkg)
	builder.WriteString("\n")
	writeImports(builder, imports)
}

func writeImports(builder *strings.Builder, imports []string) {
	if len(imports) == 0 {
		return
	}
	sorted := append([]string{}, imports...)
	sort.Strings(sorted)
	builder.WriteString("\nimport (\n")
	for _, path := range sorted {
		fmt.Fprintf(builder, "\t%q\n", path)
	}
	builder.WriteString(")\n")
}

func commentText(text string) string {
	cleaned := strings.Join(strings.Fields(text), " ")
	if cleaned == "" {
		return "the API"
	}
	return cleaned
}

func (a *analysis) typesUseRawJSON() bool {
	for _, plan := range a.types {
		if strings.Contains(plan.Inner, "json.RawMessage") {
			return true
		}
		for _, field := range plan.Fields {
			if strings.Contains(field.GoType, "json.RawMessage") {
				return true
			}
		}
	}
	return false
}

func (a *analysis) usesErrorJSON() bool {
	for _, key := range a.errorOrder {
		if a.errorDefs[key].Content == "json" {
			return true
		}
	}
	return false
}
